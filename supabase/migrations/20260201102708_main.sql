CREATE OR REPLACE FUNCTION public.get_carbon_stats(time_bucket text)
 RETURNS TABLE(period date, average_co2 numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT 
        -- On convertit le résultat du tronquage en type DATE
        date_trunc(time_bucket, h.date)::DATE AS period,
        ROUND(AVG(h.score)::numeric, 2) AS average_co2
    FROM 
        public.carbon_score_history h
    GROUP BY 
        period
    ORDER BY 
        period ASC;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.get_community_carbon_stats(time_bucket text)
 RETURNS TABLE(community_name text, period timestamp without time zone, average_co2 numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT 
        c.name::text AS community_name,
        date_trunc(time_bucket, h.date) AS period,
        AVG(h.score)::numeric AS average_co2
    FROM carbon_score_history h
    JOIN users u ON h.user_id = u.id
    JOIN communities c ON u.community_id = c.id
    GROUP BY c.name, period
    ORDER BY period DESC, community_name;
END;
$function$
;

